// 相談窓口情報の一元管理(T46 / R-03 の構造化)
//
// 【lastVerified の初期値について】
//   「未確認」を表す空文字列や null ではなく、About ページ掲載開始日(2026-07-08)を
//   初期値とする。理由:
//   - 空文字を使うと「まだ一度も確認されていない」という情報が CI テストで分かるが、
//     今回の構造化タスクは「番号の正しさの変更はしない・値は現状のまま」の前提であり、
//     掲載当初から人間が公式サイト確認するよう human-todo に既に記録されている。
//   - 空文字 / null にすると 180 日判定が「1970-01-01 からの経過」扱いとなり、
//     CI が即日失敗して警報疲れを起こす。
//   - 掲載開始日を初期値にすることで「この日以降に確認されていない」という最悪の
//     見積もりが残り、180 日(2026-12-05 頃)を超えた時点で CI が機械的に教えてくれる。
//   - 実際に公式サイトで確認が取れたら、lastVerified を確認した当日の日付に更新し
//     コミットすること。その日付が「確認の証跡」になる。
//
// human-todo: 各窓口の電話番号・URL を公式サイトで確認し、
//             lastVerified を確認日(YYYY-MM-DD)に更新してコミットしてください。

export interface SupportContact {
  /** 窓口の名称 */
  name: string;
  /**
   * 電話番号。フリーダイヤル等(0120-XXX-XXX 形式)。
   * 電話番号のない窓口は省略(undefined)。
   */
  phone?: string;
  /** UI に表示する補足説明(受付時間・利用方法など) */
  detail: string;
  /** 外部リンク先 URL。https のみ許可。リンクのない窓口は null。 */
  href: string | null;
  /**
   * 人間が公式サイトで情報(電話番号・URL)を確認した最終日(YYYY-MM-DD)。
   * この日付を更新することがリリースチェックリスト 2-A の「確認の証跡」になる。
   * 初期値は About 掲載開始日(2026-07-08)。未来日付は設定しないこと。
   */
  lastVerified: string;
}

